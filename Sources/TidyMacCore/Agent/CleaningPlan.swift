import Foundation

/// Action to be taken on matching items.
public enum PlannedAction: String, Codable, Sendable, CaseIterable {
    case trash = "trash"
    case review = "review"
    case move = "move"
}

/// Filter criteria to identify candidate files.
public struct CleaningFilter: Codable, Sendable, Equatable {
    public var categories: [ScanCategory]?
    public var extensions: [String]?
    public var minimumAgeDays: Int?
    public var minimumSizeBytes: Int64?
    public var nameContains: String?
    
    public init(
        categories: [ScanCategory]? = nil,
        extensions: [String]? = nil,
        minimumAgeDays: Int? = nil,
        minimumSizeBytes: Int64? = nil,
        nameContains: String? = nil
    ) {
        self.categories = categories
        self.extensions = extensions
        self.minimumAgeDays = minimumAgeDays
        self.minimumSizeBytes = minimumSizeBytes
        self.nameContains = nameContains
    }
}

/// Single actionable step in a cleaning plan.
public struct CleaningPlanStep: Codable, Sendable, Identifiable, Equatable {
    public let id: UUID
    public let targetFolder: String
    public let filter: CleaningFilter
    public let action: PlannedAction
    public let destinationFolder: String?
    public let explanation: String
    
    public init(
        id: UUID = UUID(),
        targetFolder: String,
        filter: CleaningFilter,
        action: PlannedAction,
        destinationFolder: String? = nil,
        explanation: String
    ) {
        self.id = id
        self.targetFolder = targetFolder
        self.filter = filter
        self.action = action
        self.destinationFolder = destinationFolder
        self.explanation = explanation
    }
}

/// A structured cleaning plan generated by AI or heuristic fallback.
public struct CleaningPlan: Codable, Sendable, Identifiable, Equatable {
    public let id: UUID
    public let userGoal: String
    public let steps: [CleaningPlanStep]
    public let summary: String
    public let isDryRun: Bool
    public let createdAt: Date
    
    public init(
        id: UUID = UUID(),
        userGoal: String,
        steps: [CleaningPlanStep],
        summary: String,
        isDryRun: Bool = true,
        createdAt: Date = Date()
    ) {
        self.id = id
        self.userGoal = userGoal
        self.steps = steps
        self.summary = summary
        self.isDryRun = isDryRun
        self.createdAt = createdAt
    }
}

/// Schema validation for incoming AI/heuristic plans.
public enum CleaningPlanSchema {
    public enum ValidationError: Error, LocalizedError, Equatable {
        case emptyGoal
        case emptySteps
        case missingTargetFolder
        case invalidDestinationFolder
        case protectedTargetFolder(String)
        case invalidFilterCriteria
        
        public var errorDescription: String? {
            switch self {
            case .emptyGoal:
                return "The plan user goal cannot be empty."
            case .emptySteps:
                return "The cleaning plan must contain at least one step."
            case .missingTargetFolder:
                return "Every plan step must declare a target folder."
            case .invalidDestinationFolder:
                return "Move actions must declare a valid non-empty destination folder."
            case .protectedTargetFolder(let path):
                return "Target folder is protected and prohibited: \(path)"
            case .invalidFilterCriteria:
                return "Filter criteria must specify at least one filter attribute."
            }
        }
    }
    
    /// Validates a plan against structural and safety requirements.
    public static func validate(_ plan: CleaningPlan) throws {
        guard !plan.userGoal.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            throw ValidationError.emptyGoal
        }
        guard !plan.steps.isEmpty else {
            throw ValidationError.emptySteps
        }
        
        for step in plan.steps {
            let target = step.targetFolder.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !target.isEmpty else {
                throw ValidationError.missingTargetFolder
            }
            
            // Prohibit system-level target directories
            let canonicalTarget = URL(fileURLWithPath: target).resolvingSymlinksInPath().path
            if canonicalTarget == "/" || canonicalTarget == "/System" || canonicalTarget == "/Library" || canonicalTarget == "/usr" || canonicalTarget == "/bin" || canonicalTarget == "/private" {
                throw ValidationError.protectedTargetFolder(target)
            }
            
            if step.action == .move {
                guard let dest = step.destinationFolder, !dest.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
                    throw ValidationError.invalidDestinationFolder
                }
            }
            
            let filter = step.filter
            let hasCategory = !(filter.categories?.isEmpty ?? true)
            let hasExtension = !(filter.extensions?.isEmpty ?? true)
            let hasAge = filter.minimumAgeDays != nil
            let hasSize = filter.minimumSizeBytes != nil
            let hasName = filter.nameContains != nil && !(filter.nameContains?.isEmpty ?? true)
            
            guard hasCategory || hasExtension || hasAge || hasSize || hasName else {
                throw ValidationError.invalidFilterCriteria
            }
        }
    }
}
